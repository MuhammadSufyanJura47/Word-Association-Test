    function startCountdown() {
      const btn = document.getElementById('startBtn');
      btn.style.display = 'none';
      let count = 3;
      document.getElementById('wordBox').textContent = count;
      const countdownInterval = setInterval(() => {
        count--;
        if (count === 0) {
          clearInterval(countdownInterval);
          enterFullscreen();
          nextWord();
        } else {
          document.getElementById('wordBox').textContent = count;
        }
      }, 1000);
    }

    function enterFullscreen() {
      const elem = document.documentElement;
      if (elem.requestFullscreen) {
        elem.requestFullscreen();
      } else if (elem.webkitRequestFullscreen) {
        elem.webkitRequestFullscreen();
      } else if (elem.msRequestFullscreen) {
        elem.msRequestFullscreen();
      }
    }

    function nextWord() {
      index++;
      if (index >= words.length) {
        document.getElementById('wordBox').textContent = 'Test Complete';
        document.getElementById('timer').textContent = '';
        document.getElementById('wordCounter').textContent = '';
        return;
      }
      document.getElementById('wordBox').textContent = words[index];
      countdown = 10;
      document.getElementById('timer').textContent = countdown;
      // Update word counter
      document.getElementById('wordCounter').textContent = `Word ${index+1} of ${totalWords}`;
      clearInterval(timer);
      timer = setInterval(updateTimer, 1000);
      playSound();
    }

    function updateTimer() {
      countdown--;
      document.getElementById('timer').textContent = countdown;
      if (countdown <= 0) {
        clearInterval(timer);
        nextWord();
      }
    }
    

